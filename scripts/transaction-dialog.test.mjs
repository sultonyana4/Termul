import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import { createTransactionDialog, transactionExplorerUrl } from '../src/transaction-dialog.js';

const html = await readFile(new URL('../index.html', import.meta.url), 'utf8');
const { window } = new JSDOM(html);
const dialog = window.document.querySelector('#transaction-dialog');
dialog.showModal = () => { dialog.open = true; };
dialog.close = () => { dialog.open = false; dialog.dispatchEvent(new window.Event('close')); };
const field = name => dialog.querySelector('[data-transaction-' + name + ']');
const ui = createTransactionDialog(dialog);
const network = { name: 'Arc Mainnet', explorerName: 'Arc Explorer', explorerUrl: 'https://explorer.arc.io' };
const hash = '0x' + 'ab'.repeat(32);
const otherNetwork = { name: 'Other EVM network', explorerName: 'Other Explorer', explorerUrl: 'https://other.example/explorer/' };
assert.equal(transactionExplorerUrl(otherNetwork, hash), 'https://other.example/explorer/tx/' + hash);
assert.equal(transactionExplorerUrl({ explorerUrl: 'http://unsafe.example' }, hash), null);
assert.equal(transactionExplorerUrl({ explorerUrl: 'https://user@unsafe.example' }, hash), null);
assert.equal(transactionExplorerUrl(network, '../bad-hash'), null);
const details = { type: 'Invoice payment', amount: '0.000000000000000001 USDC', detail: 'Invoice fixture', network, scope: 'fixture' };
const origin = window.document.querySelector('#connect-wallet');
origin.focus();
const payment = ui.begin(details);
assert.equal(dialog.open, true);
assert.equal(window.document.activeElement, field('done'));
for (const phase of ['approval', 'submitted', 'pending']) {
  payment.update(phase, { verifiedHash: hash });
  assert.equal(dialog.dataset.phase, phase);
  assert.equal(field('proof').hidden, true);
  assert.equal(field('explorer').hasAttribute('href'), false);
}
payment.update('confirmed', { verifiedHash: 'invalid' });
assert.equal(dialog.dataset.phase, 'pending');
payment.update('pending', { referenceHash: hash });
assert.equal(field('proof').hidden, false);
assert.equal(field('proof-label').textContent, 'Submitted transaction reference');
assert.equal(field('copy').hidden, true);
ui.update('unrelated', 'confirmed', { verifiedHash: hash });
assert.equal(dialog.dataset.phase, 'pending');
ui.update('fixture', 'confirmed', { verifiedHash: hash });
assert.equal(dialog.dataset.phase, 'confirmed');
assert.equal(field('proof').hidden, false);
assert.equal(field('hash').textContent, hash);
assert.equal(field('type').textContent, details.type);
assert.equal(field('amount').textContent, details.amount);
assert.equal(field('explorer').href, 'https://explorer.arc.io/tx/' + hash);
let copy;
window.navigator.clipboard = { writeText: async value => { copy = value; } };
field('copy').click();
await Promise.resolve();
assert.equal(copy, hash);
assert.equal(field('copy-status').textContent, 'Transaction hash copied.');
dialog.close();
assert.equal(window.document.activeElement, origin);
const next = ui.begin({ ...details, type: 'Invoice creation', scope: undefined });
payment.update('failed');
assert.equal(dialog.dataset.phase, 'preparing');
assert.equal(field('proof').hidden, true);
next.update('rejected');
assert.equal(field('title').textContent, 'Wallet request declined');
assert.equal(field('proof').hidden, true);
const final = ui.begin(details);
final.update('failed');
assert.equal(field('title').textContent, 'Transaction failed');
ui.clear();
assert.equal(dialog.open, false);
window.close();
console.log('Transaction dialog phases, verified proof, explorer selection, clipboard and focus passed.');
